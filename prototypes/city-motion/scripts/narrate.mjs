// Narrate each scene with edge-tts (word timestamps), size every scene to its narration on the beat grid
// and write the data module the page renders.
// usage: node scripts/narrate.mjs <ibge-code>   ->   out/narration/*.mp3, out/narration.json, src/data/episode.js
import { execFile } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const run = promisify(execFile);
const ROOT = resolve(fileURLToPath(import.meta.url), '..', '..');
const TTS = resolve(ROOT, '..', '..', 'scripts', 'comic_tts.py'); // the repo's edge-tts wrapper
const BEAT = 0.5; // 120 BPM; the transition overlap is one beat (src/engine/timeline.js)
const code = process.argv[2];
if (!/^\d{7}$/.test(code ?? '')) { console.error('usage: node scripts/narrate.mjs <ibge-code>'); process.exit(2); }

const city = JSON.parse(await readFile(join(ROOT, 'data', `${code}.json`), 'utf8'));
const script = JSON.parse(await readFile(join(ROOT, 'episodes', `${code}.json`), 'utf8'));
const dir = join(ROOT, 'out', 'narration');
await mkdir(dir, { recursive: true });
await mkdir(join(ROOT, 'src', 'data'), { recursive: true });

const beats = s => Math.ceil(s / BEAT - 1e-6) * BEAT;
// edge-tts glues a number to its neighbour ("1.139.047 habitantes" is one boundary): split it so captions
// stay short, sharing the time by spoken weight (a digit takes far longer to say than a letter).
function splitToken({ word, start, end }) {
  const parts = word.split(/\s+/).filter(Boolean);
  const weight = p => [...p].reduce((n, ch) => n + (/\d/.test(ch) ? 4 : 1), 0);
  const total = parts.reduce((n, p) => n + weight(p), 0);
  let at = start;
  return parts.map(p => {
    const to = at + (end - start) * weight(p) / total;
    const out = { word: p, start: +at.toFixed(3), end: +to.toFixed(3) };
    at = to;
    return out;
  });
}

const scenes = [];
for (const [i, scene] of script.scenes.entries()) {
  const base = join(dir, String(i + 1).padStart(2, '0'));
  await writeFile(`${base}.txt`, scene.narration);
  await run('uv', ['run', '--quiet', '--with', 'edge-tts', 'python', TTS, `${base}.txt`, `${base}.mp3`, `${base}.json`, script.voice]);
  const words = JSON.parse(await readFile(`${base}.json`, 'utf8'));
  if (!words.length) throw new Error(`scene ${i + 1}: edge-tts returned no word timestamps`);
  const { stdout } = await run('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', `${base}.mp3`]);
  const spoken = Math.max(Number(stdout), words.at(-1).end);
  const last = i === script.scenes.length - 1;
  // narration starts after the incoming transition; the scene holds 0.4s after the last word, then one beat
  // of overlap for the next scene (or a 2s tail for the final impact of the music)
  const lead = i === 0 ? 0.3 : BEAT + 0.1;
  const dur = beats(lead + spoken + 0.4) + (last ? 2 : BEAT);
  scenes.push({ ...scene, lead, dur, words: words.flatMap(splitToken) });
  console.error(`scene ${i + 1} ${scene.type}: narration ${spoken.toFixed(2)}s -> ${dur}s`);
}

const { history, sources, ...cityData } = city;
const episode = { series: script.series, episode: script.episode, city: cityData, scenes };
await writeFile(join(ROOT, 'src', 'data', 'episode.js'), `// generated by scripts/narrate.mjs - do not edit\nexport default ${JSON.stringify(episode)};\n`);
await writeFile(join(ROOT, 'out', 'narration.json'), `${JSON.stringify(scenes.map((s, i) => ({ file: join(dir, `${String(i + 1).padStart(2, '0')}.mp3`), lead: s.lead })))}\n`);
console.error(`episode: ${scenes.length} scenes, ${scenes.reduce((n, s) => n + s.dur, 0) - BEAT * (scenes.length - 1)}s`);
